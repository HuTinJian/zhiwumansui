/* ============================================================
   织雾满穗 · 怀旧版演示提示（2026-10-30 更新）
   ------------------------------------------------------------
   上一版理解错了站主要求：把旧版所有按钮都拦住，点哪都只弹提示，
   结果连搜索、筛选、收藏、隔离、复制这些正常浏览都用不了。
   现在改成：旧版交互照常可以点，只在「真正会写到新版 / 跳转出去」的
   最后一步调用这里的提示，例如：
     · 反馈提交 —— 显示旧版成功页，但不提交；
     · 试听「确认跳转」 —— 只提示，不打开 Roblox、不计热度；
     · 来源问卷 —— 只存本地，不上报。
   本文件只提供 window.legacyNotice，不做任何全局拦截。

   【回退办法】删掉本文件，并删掉三个旧版页面里的
   <script src="js/legacy-demo.js"></script> 那一行；
   反馈/试听的处理再按各自注释里的回退说明恢复即可。
   ============================================================ */
(function () {
  'use strict';

  var DEFAULT = '🕰️ 怀旧版只作展示，这个操作不会生效。';

  window.legacyNotice = function (text, duration) {
    var msg = text || DEFAULT;
    if (typeof window.showToast === 'function') {
      window.showToast(msg, duration || 3000);
    } else {
      /* common.js 万一没加载成功，至少别静默无反应 */
      window.alert(msg);
    }
  };
})();
